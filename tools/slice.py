#!/usr/bin/env python3
"""Slice a 3MF/STL with the PrusaSlicer CLI using profiles in profiles/.

Usage:
  python tools/slice.py out/part/part.3mf [--profile profiles/mk3s_pla_0.20mm.ini]
                        [--set key=value ...] [--3mf]

--set passes PrusaSlicer config overrides using config-file keys, e.g.
  --set fill_density=40% --set perimeters=4 --set support_material=1
Note: the CLI re-arranges objects on the bed; model layouts don't decide where parts slice.
--3mf also writes <model>_project.3mf: the model plus the settings it was sliced with, to
open in PrusaSlicer (needs a .3mf input; PrusaSlicer's own --export-3mf drops the settings).
Prints JSON with output paths, estimates parsed from the G-code, and any PrusaSlicer
print warnings (e.g. "Low bed adhesion"), which the GUI would show but the CLI doesn't fail on.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import tempfile
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_PROFILE = ROOT / "profiles" / "mk3s_pla_0.20mm.ini"


def find_slicer() -> str:
    env = os.environ.get("PRUSA_SLICER")
    if env:
        found = shutil.which(env) or (env if Path(env).exists() else None)
        if not found:
            sys.exit(f"PRUSA_SLICER is set to {env!r}, which doesn't exist")
        return found
    for name in ("prusa-slicer", "PrusaSlicer",
                 "/Applications/PrusaSlicer.app/Contents/MacOS/PrusaSlicer"):
        if shutil.which(name) or Path(name).exists():
            return shutil.which(name) or name
    sys.exit("PrusaSlicer not found; set PRUSA_SLICER to its executable")


def estimates(gcode: Path) -> dict:
    keys = {
        "estimated printing time (normal mode)": "time",
        "filament used [mm]": "filament_mm",
        "filament used [g]": "filament_g",
        "total filament used [g]": "filament_g",
        "filament_type": "filament_type",
        "layer_height": "layer_height",
        "fill_density": "fill_density",
        "perimeters": "perimeters",
        "support_material": "supports",
    }
    found = {}
    with open(gcode, errors="replace") as f:
        for line in f:
            m = re.match(r";\s*([^=]+?)\s*=\s*(.+)", line)
            if m and m.group(1) in keys:
                found[keys[m.group(1)]] = m.group(2).strip()
    return found


def _config_lines(gcode: Path) -> list[str]:
    """Lines of the config block PrusaSlicer writes at the end of the G-code
    (between `; prusaslicer_config = begin` and `= end`)."""
    out, inside = [], False
    with open(gcode, errors="replace") as f:
        for line in f:
            if line.startswith("; prusaslicer_config = "):
                inside = line.strip().endswith("begin")
            elif inside and re.match(r"; [a-z0-9_]+ = ", line):
                out.append(line if line.endswith("\n") else line + "\n")
    return out


def gcode_config(gcode: Path) -> dict:
    """The G-code's config block as {key: value}: the settings actually used."""
    cfg = {}
    for line in _config_lines(gcode):
        k, _, v = line[2:].partition(" = ")
        cfg[k] = v.strip()
    return cfg


def write_project(model: Path, gcode: Path, out_3mf: Path) -> None:
    """Project 3MF = the model's 3MF plus the settings the G-code was sliced with.
    PrusaSlicer's --export-3mf (2.7) writes geometry only, with no Slic3r_PE.config,
    so the GUI would open it with whatever presets happen to be selected."""
    cfg = "; generated by PrusaSlicer\n\n" + "".join(_config_lines(gcode))
    with zipfile.ZipFile(model) as zi, zipfile.ZipFile(out_3mf, "w", zipfile.ZIP_DEFLATED) as zo:
        for item in zi.infolist():
            if item.filename != "Metadata/Slic3r_PE.config":
                zo.writestr(item, zi.read(item))
        zo.writestr("Metadata/Slic3r_PE.config", cfg)


def slicer_warnings(output: str) -> list[str]:
    """PrusaSlicer's "print warning:" blocks (stability, supports needed, empty layers),
    one string each: "title: paragraph; paragraph", lines within a paragraph joined by
    ", " (a paragraph is an object name and its issues, or an issue and its objects).
    The CLI prints them but still exits 0, so they'd be lost otherwise. Pass one
    stream at a time; a block ends at the next progress line, the export message, or
    the end of the stream."""
    blocks, cur = [], None
    for line in output.splitlines():
        if re.match(r"\s*(print|object) warning:", line, re.I):
            cur = [line.strip(), []]
            blocks.append(cur)
        elif cur is not None:
            if re.match(r"\s*(\d+ => |Slicing result exported)", line):
                cur = None
            elif not line.strip():
                if cur[-1]:
                    cur.append([])                 # blank line separates paragraphs
            else:
                cur[-1].append(line.strip())
    out = []
    for title, *paras in blocks:
        body = "; ".join(", ".join(p) for p in paras if p)
        out.append(f"{title} {body}" if body else title)
    return out


def slice_model(model: Path, profile: Path = DEFAULT_PROFILE, overrides=(), project=False) -> dict:
    slicer = find_slicer()
    out_gcode = model.with_suffix(".gcode")
    out_gcode.unlink(missing_ok=True)          # never report a stale G-code
    out_gcode.with_suffix(".gcode.tmp").unlink(missing_ok=True)   # left by a failed export
    # Fail on invalid values (e.g. fill_pattern=gyroidd) instead of letting
    # PrusaSlicer silently substitute another value.
    base = [slicer, "--config-compatibility", "disable", "--load", str(profile)]
    # Validate every override before touching the filesystem.
    pairs = []
    for o in overrides:
        k, sep, v = o.partition("=")
        if not sep or not k.strip():
            raise SystemExit(f"--set expects key=value, got {o!r}")
        if "\n" in o or "\r" in o:
            raise SystemExit(f"--set value must be one line (use \\n for G-code newlines): {o!r}")
        pairs.append((k.strip(), v.strip()))
    tmp = None
    try:
        if pairs:
            # Overrides go in a second config file (key = value, PrusaSlicer's own format).
            # Passing them as CLI flags breaks boolean options, which are bare flags.
            tmp = tempfile.NamedTemporaryFile("w", suffix=".ini", delete=False, encoding="utf-8")
            tmp.write("".join(f"{k} = {v}\n" for k, v in pairs))
            tmp.close()
            base += ["--load", tmp.name]
        cmd = base + ["--export-gcode", "--output", str(out_gcode), str(model)]
        r = subprocess.run(cmd, capture_output=True, text=True)
        result = {"cmd": cmd, "returncode": r.returncode, "overrides": dict(pairs)}
        # Collected before any error return: warnings like "Empty layer" often explain a failure.
        warns = slicer_warnings(r.stdout) + slicer_warnings(r.stderr)
        if warns:
            result["warnings"] = warns
        if r.returncode != 0 or not out_gcode.exists():
            result["error"] = (r.stderr or r.stdout)[-3000:]
            return result
        # PrusaSlicer silently ignores unknown keys; every override must appear in
        # the G-code's config block, or it was misspelled.
        config = gcode_config(out_gcode)
        unknown = [k for k, _ in pairs if k not in config]
        if unknown:
            result["error"] = f"unknown PrusaSlicer config key(s), ignored by the slicer: {unknown}"
            return result
        result["gcode"] = str(out_gcode)
        result["estimates"] = estimates(out_gcode)
        if project:
            out_3mf = model.with_name(model.stem + "_project.3mf")
            out_3mf.unlink(missing_ok=True)
            if model.suffix.lower() != ".3mf":
                result["project_3mf_error"] = "--3mf needs a .3mf input (build.py writes one)"
            else:
                write_project(model, out_gcode, out_3mf)
                result["project_3mf"] = str(out_3mf)
        return result
    finally:
        if tmp:
            Path(tmp.name).unlink(missing_ok=True)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("model", type=Path)
    ap.add_argument("--profile", type=Path, default=DEFAULT_PROFILE)
    ap.add_argument("--set", action="append", default=[], metavar="KEY=VALUE")
    ap.add_argument("--3mf", dest="project", action="store_true")
    a = ap.parse_args()
    res = slice_model(a.model, a.profile, a.set, a.project)
    print(json.dumps(res, indent=2))
    sys.exit(0 if "gcode" in res else 1)
